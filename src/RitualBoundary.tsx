import { Component, type ReactNode } from "react";

// A failed optional animation chunk must never hide an acknowledged send or opened note.
export default class RitualBoundary extends Component<
  { children: ReactNode; fallback: ReactNode },
  { failed: boolean }
> {
  state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  render() {
    return this.state.failed ? this.props.fallback : this.props.children;
  }
}
